import { expect, test } from "./support/coverage"
import { createJobSearchWorkspace } from "./support/workspaces"

test("Given a private workspace recovery file, when created then inspected and restored, then words appear only after creation and replacement stays explicit", async ({ page }) => {
  await page.goto("/")
  await createJobSearchWorkspace(page, "Private recovery board")
  await page.getByRole("button", { name: "Sync", exact: true }).click()
  const sync = page.getByRole("dialog", { name: "Device sync" })
  await sync.getByRole("tab", { name: "Backups", exact: true }).click()
  const backups = sync.getByRole("region", { name: "Private workspace recovery" })
  await expect(backups.getByRole("button", { name: "Create private recovery backup", exact: true })).toBeVisible()
  await expect(backups.getByLabel("Recovery words", { exact: true })).toHaveCount(0)
  const downloadEvent = page.waitForEvent("download")
  await backups.getByRole("button", { name: "Create private recovery backup", exact: true }).click()
  const file = await (await downloadEvent).path()
  const words = await backups.getByLabel("Recovery words", { exact: true }).inputValue()
  expect(words.trim().length).toBeGreaterThan(0)
  await backups.locator('input[type="file"]').setInputFiles(file!)
  await backups.getByLabel("Recovery words to inspect").fill("incorrect words")
  await backups.getByRole("button", { name: "Inspect recovery file", exact: true }).click()
  await expect(backups.getByRole("alert")).toBeVisible()
  await expect(backups.getByRole("button", { name: "Restore recovered workspace", exact: true })).toHaveCount(0)
  await backups.getByLabel("Recovery words to inspect").fill(words)
  await backups.getByRole("button", { name: "Inspect recovery file", exact: true }).click()
  const preview = backups.getByRole("region", { name: "Recovery preview" })
  await expect(preview.getByText(/Workspace:\s*Private recovery board/)).toBeVisible()
  await expect(backups.getByText(/complete backup/i)).toBeVisible()
  const replace = backups.getByLabel("Replace an existing local copy of this workspace")
  await expect(replace).toBeVisible()
  await expect(backups.getByRole("button", { name: "Restore recovered workspace", exact: true })).toBeDisabled()
  await replace.check()
  await backups.getByRole("button", { name: "Restore recovered workspace", exact: true }).click()
  await expect(backups.getByRole("status")).toContainText(/restored/i)
  await expect(preview.getByText(/Workspace:\s*Private recovery board/)).toBeVisible()
})

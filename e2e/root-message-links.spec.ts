import { expect, test } from "./support/coverage"
import { ensureJobSearchWorkspace } from "./support/workspaces"

for (const width of [390, 1440]) test(`Given a root message with replies at ${width}px, when its copied local link reloads, then its paper highlight reveals the root and its siblings without blue frames`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto("/")
  await ensureJobSearchWorkspace(page)
  await page.getByRole("button", { name: "Workspace chat", exact: true }).filter({ visible: true }).click()
  const chat = page.getByRole("dialog", { name: "Workspace chat", exact: true })
  await chat.getByRole("textbox", { name: "Message", exact: true }).fill("Linked conversation root")
  await chat.getByRole("button", { name: "Send message", exact: true }).click()
  await expect(chat.getByText("Saving locally…", { exact: true })).toHaveCount(0)
  const root = chat.locator(".chat-message-item").filter({ hasText: "Linked conversation root" })
  const rootId = await root.getAttribute("data-message-id")
  await root.getByRole("button", { name: "Reply to message" }).click()
  const thread = page.getByRole("dialog", { name: "Discussion · replies", exact: true })
  await thread.getByRole("textbox", { name: "Message", exact: true }).fill("First root reply")
  await thread.getByRole("button", { name: "Send message", exact: true }).click()
  await expect(thread.getByText("Saving locally…", { exact: true })).toHaveCount(0)
  await thread.getByRole("button", { name: "Close", exact: true }).click()
  await page.evaluate(() => {
    Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async (url: string) => { sessionStorage.setItem("root-message-link", url) } } })
  })
  await chat.locator(`[data-message-id="${rootId}"]`).getByRole("button", { name: "Copy link" }).click()
  await expect(chat.getByRole("button", { name: "Copied ✓", exact: true })).toBeVisible()
  const url = await page.evaluate(() => sessionStorage.getItem("root-message-link"))
  expect(url).toBeTruthy()
  await page.goto(url!)
  const discussion = page.getByRole("dialog", { name: "Discussion · replies", exact: true })
  await expect(discussion).toBeVisible()
  await expect(discussion.locator(`[data-message-id="${rootId}"]`)).toHaveClass(/is-linked-message/)
  await expect(discussion.getByText("First root reply", { exact: true })).toBeVisible()
  await expect(discussion.locator(".chat-message-item")).toHaveCount(2)
  const linked = discussion.locator(`[data-message-id="${rootId}"]`)
  await expect(discussion).toHaveCSS("border-top-color", "rgb(23, 23, 23)")
  await expect(linked).toHaveCSS("border-image-source", /ink-surface.*#soft/)
  await expect(discussion.locator(".chat-message-item").last()).not.toHaveCSS("border-image-source", /#soft/)
  await expect(linked).not.toHaveCSS("outline-color", "rgb(31, 111, 235)")
  await page.keyboard.press("Tab")
  await discussion.locator(".spatial-titlebar").focus()
  await expect(discussion.locator(".spatial-titlebar")).toHaveCSS("outline-color", "rgb(23, 107, 77)")
  await expect(discussion.locator(".spatial-titlebar")).toHaveCSS("outline-style", "solid")
  await expect(discussion).toHaveCSS("border-top-color", "rgb(23, 23, 23)")
  await discussion.screenshot({ path: info.outputPath(`paper-message-${width}.png`) })
  // Closing an unrelated window must preserve the conversation link.
  await page.getByRole("button", { name: "Workspace chat", exact: true }).filter({ visible: true }).focus()
  await page.keyboard.press("Enter")
  await chat.locator(".spatial-titlebar").focus()
  await chat.getByRole("button", { name: "Close", exact: true }).click()
  await expect(page).toHaveURL(url!)
  await discussion.getByRole("button", { name: "Close", exact: true }).click()
  await expect(page).toHaveURL(new URL("/", url!).toString())
  await expect(discussion).toHaveCount(0)
  await page.goto(url!)
  await expect(discussion.locator(`[data-message-id="${rootId}"]`)).toHaveClass(/is-linked-message/)
  await expect(discussion.locator(".chat-message-item")).toHaveCount(2)
})

import { expect, test } from "./support/coverage"

test("Given a blank board, when colors are configured in JSON, then unique defaults and saved colors survive reload and mobile", async ({ page }) => {
  await page.goto("/")
  await page.getByRole("button", { name: "Open workspaces" }).click()
  await page.getByRole("button", { name: "New workspace" }).click()
  const create = page.getByRole("dialog", { name: "Create workspace" })
  await create.getByLabel("Title").fill("Colors")
  await create.getByRole("radio", { name: "Blank board" }).check()
  await create.getByRole("button", { name: "Create" }).click()
  await expect(create).toBeHidden()
  const board = page.getByRole("region", { name: "Colors", exact: true })
  await expect(board).toBeVisible()
  const columns = board.locator(":scope > .column")
  await expect(columns).toHaveCount(3)
  const colors = await columns.evaluateAll(nodes => nodes.map(node => getComputedStyle(node).getPropertyValue("--column-hatch-color").trim()))
  expect(new Set(colors).size).toBe(colors.length)
  await page.getByRole("button", { name: "Settings", exact: true }).click()
  const settings = page.getByRole("dialog", { name: "Settings" })
  await settings.getByRole("tab", { name: "Workspace", exact: true }).click()
  await settings.getByText("settings.json", { exact: true }).click()
  const editor = settings.getByLabel("Workspace settings JSON")
  const config = JSON.parse(await editor.inputValue())
  config.board.columns[0].color = "yellow"
  await editor.fill(JSON.stringify(config))
  await expect(settings.getByRole("button", { name: "Apply JSON" })).toBeDisabled()
  await expect(settings.getByText("/board/columns/0/color", { exact: true })).toBeVisible()
  config.board.columns[0].color = "#123abc"
  await editor.fill(JSON.stringify(config))
  await settings.getByRole("button", { name: "Apply JSON" }).click()
  await expect(settings).toBeHidden()
  const column = page.locator(`.column[data-column-id="${config.board.columns[0].id}"]`)
  await expect(column).toHaveCSS("--column-hatch-color", "#123abc")
  await page.reload()
  await expect(column).toHaveCSS("--column-hatch-color", "#123abc")
  await page.screenshot({ path: "tmp/column-colors-desktop.png" })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(column).toHaveCSS("--column-hatch-color", "#123abc")
})

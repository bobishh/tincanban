import { expect, test } from "./support/coverage"

test("Given an abandoned offline-server removal, when I stop its retry after review, then retain unconfirmed history across reload without another server request", async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 900 })
  await page.goto("/")
  await expect(page.getByLabel("Workspace role: owner")).toBeVisible()
  await page.evaluate(async () => (await import("/e2e/support/syncDeviceRemoval.ts")).mountSyncDeviceRemoval())
  const sync = page.getByRole("dialog", { name: "Device sync" })
  const old = sync.locator(".mesh-device").filter({ hasText: "Device old-devi" })
  await old.getByRole("button", { name: "Remove my device", exact: true }).click()
  await page.getByRole("dialog", { name: "Remove my device confirmation" }).getByRole("button", { name: "Confirm removal of my device", exact: true }).click()
  await old.getByRole("button", { name: "Stop retrying this server", exact: true }).click()
  const review = page.getByRole("dialog", { name: "Stop server removal confirmation" })
  await expect(review).toContainText("https://offline.example")
  await expect(review).toContainText("Server access is not confirmed revoked")
  await review.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(old).toContainText("Server offline; retry when reachable")
  await old.getByRole("button", { name: "Stop retrying this server", exact: true }).click()
  await review.getByRole("button", { name: "Stop retrying", exact: true }).click()
  await sync.getByText("Removed device records (1)", { exact: true }).click()
  const history = sync.locator(".removed-device-history")
  await expect(history).toContainText("Server access is not confirmed revoked")
  await expect(history).toContainText("https://offline.example · Removal stopped on this device")
  expect(await page.evaluate(() => window.syncRemovalCalls)).toEqual(["board|old-device", "https://online.example|old-device", "https://offline.example|old-device"])
  await page.reload()
  await expect(page.getByLabel("Workspace role: owner")).toBeVisible()
  await page.evaluate(async () => (await import("/e2e/support/syncDeviceRemoval.ts")).mountSyncDeviceRemoval(false))
  await sync.getByText("Removed device records (1)", { exact: true }).click()
  await expect(history).toContainText("https://offline.example · Removal stopped on this device")
  expect(await page.evaluate(() => window.syncRemovalCalls)).toEqual([])
  await history.scrollIntoViewIfNeeded()
  await page.screenshot({ animations: "disabled", path: info.outputPath("device-removal-stopped.png") })
})

for (const width of [1280, 390]) test(`Given my two device labels at ${width}px and two servers, when one server is offline, then preserve pending removal across reload and separate completed records from active devices`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto("/")
  await expect(page.getByLabel("Workspace role: owner")).toBeVisible()
  await page.evaluate(async () => (await import("/e2e/support/syncDeviceRemoval.ts")).mountSyncDeviceRemoval())
  const sync = page.getByRole("dialog", { name: "Device sync" })
  const old = sync.locator(".mesh-device").filter({ hasText: "Device old-devi" })
  await expect(old).toContainText("Browser / OS unknown")
  await expect(old).not.toContainText("Last seen")
  await expect(sync.getByRole("button", { name: "Remove my device", exact: true })).toHaveCount(1)
  await old.getByRole("button", { name: "Remove my device", exact: true }).click()
  const confirm = page.getByRole("dialog", { name: "Remove my device confirmation" })
  await expect(confirm).toContainText("old-device")
  await expect(confirm).not.toContainText("Valiant Squirrel")
  await expect(confirm.getByRole("list", { name: "Confirmed device removal scope" })).toContainText("Synthetic board")
  await expect(confirm.getByRole("list", { name: "Confirmed device removal scope" })).toContainText("https://offline.example")
  await confirm.getByRole("button", { name: "Confirm removal of my device", exact: true }).click()
  await expect(old).toContainText("https://online.example · Rusty access revoked")
  await expect(old).toContainText("Server offline; retry when reachable")
  await expect(old.getByRole("button", { name: "Retry device removal", exact: true })).toBeEnabled()
  await old.scrollIntoViewIfNeeded()
  await page.screenshot({ animations: "disabled", path: info.outputPath(`device-removal-pending-${width}.png`) })
  expect(await page.evaluate(() => window.syncRemovalCalls)).toEqual(["board|old-device", "https://online.example|old-device", "https://offline.example|old-device"])
  await page.reload()
  await expect(page.getByLabel("Workspace role: owner")).toBeVisible()
  await page.evaluate(async () => (await import("/e2e/support/syncDeviceRemoval.ts")).mountSyncDeviceRemoval(false))
  await expect(old).toContainText("Server offline; retry when reachable")
  await old.getByRole("button", { name: "Retry device removal", exact: true }).click()
  await confirm.getByRole("button", { name: "Confirm removal of my device", exact: true }).click()
  await expect(sync.locator(".mesh-device-list")).not.toContainText("Device old-devi")
  await expect(sync.locator(".mesh-member")).toContainText("1 device")
  await sync.getByText("Removed device records (1)", { exact: true }).click()
  const history = sync.locator(".removed-device-history")
  await expect(history).toContainText("Device old-devi")
  await expect(history).toContainText("Access revoked in listed workspaces and Rusty servers")
  await expect(history.getByRole("button", { name: "Retry device removal", exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => window.syncRemovalCalls)).toEqual(["https://offline.example|old-device"])
  await history.scrollIntoViewIfNeeded()
  await page.screenshot({ animations: "disabled", path: info.outputPath(`device-removal-complete-${width}.png`) })
})

import { expect, test, type Page } from "./support/coverage"

async function createBoardAndItem(page: Page) {
  await page.goto("/")
  await page.getByRole("button", { name: "Open workspaces" }).click()
  await page.getByRole("button", { name: "New workspace" }).click()
  const workspace = page.getByRole("dialog", { name: "Create workspace" })
  await workspace.getByLabel("Title").fill("History board")
  await workspace.getByRole("radio", { name: "Blank board" }).check()
  await workspace.getByRole("button", { name: "Create" }).click()
  await page.getByRole("button", { name: "Add item to To do" }).click()
  const item = page.getByRole("dialog", { name: "Item details" })
  await item.getByLabel("Title *").fill("Reversible item")
  await item.getByRole("button", { name: "Save item" }).click()
  await expect(item).toBeHidden()
}

async function moveToDoing(page: Page) {
  await page.evaluate(() => window.scrollTo(0, 0))
  const source = await page.locator('.lead-card[data-item-id]:has-text("Reversible item")').boundingBox()
  const target = await page.getByRole("region", { name: "Doing" }).locator(".card-stack").boundingBox()
  if (!source || !target) throw new Error("Missing drag bounds")
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
  await page.mouse.down()
  await page.mouse.move(target.x + target.width / 2, target.y + Math.min(28, target.height / 2), { steps: 12 })
  await page.mouse.up()
  await expect(page.getByRole("region", { name: "Doing" }).getByText("Reversible item")).toBeVisible()
}

test("Given a moved item, when restore fails then retries, then current placement is preserved until durable compensation succeeds", async ({ page }) => {
  await createBoardAndItem(page)
  await moveToDoing(page)
  await page.getByRole("button", { name: "Open Reversible item" }).click()
  const detail = page.getByRole("dialog", { name: "Item overview" })
  await detail.getByRole("button", { name: "History", exact: true }).click()
  const history = page.getByRole("dialog", { name: "Item history", exact: true })
  const restore = history.locator(".item-history-entry").filter({ hasText: "createItem" })
    .getByRole("button", { name: "Restore this version" })
  await expect(restore).toBeVisible()
  await test.step("Failed restore leaves the committed placement unchanged", async () => {
    await page.evaluate(() => { (window as any).__TINCANBAN_INJECT_STORAGE_FAILURE__ = true })
    await restore.click()
    await expect(history.getByRole("alert")).toContainText("Restore failed")
    await history.getByRole("button", { name: "Close history", exact: true }).click()
    await detail.getByRole("button", { name: "Close detail" }).click()
    await expect(page.getByRole("region", { name: "Doing" }).getByText("Reversible item")).toBeVisible()
    await expect(page.getByRole("region", { name: "To do" }).locator(".lead-card")).toHaveCount(0)
  })
  await test.step("Retry restores creation state and survives reload", async () => {
    await page.evaluate(() => { (window as any).__TINCANBAN_INJECT_STORAGE_FAILURE__ = false })
    await page.getByRole("button", { name: "Open Reversible item" }).click()
    await detail.getByRole("button", { name: "History", exact: true }).click()
    await restore.click()
    await expect(history.getByText("Version restored")).toBeVisible()
    await history.getByRole("button", { name: "Close history", exact: true }).click()
    await detail.getByRole("button", { name: "Close detail" }).click()
    await expect(page.getByRole("region", { name: "To do" }).getByText("Reversible item")).toBeVisible()
    await expect(page.getByRole("region", { name: "Doing" }).locator(".lead-card")).toHaveCount(0)
    await page.reload()
    await expect(page.getByRole("region", { name: "To do" }).getByText("Reversible item")).toBeVisible()
    await expect(page.getByRole("region", { name: "Doing" }).locator(".lead-card")).toHaveCount(0)
  })
})

test("Given a board without an archive, when earlier history is requested, then explain the empty result and preserve its current item", async ({ page }) => {
  await createBoardAndItem(page)
  await page.getByRole("button", { name: "Open Reversible item" }).click()
  const detail = page.getByRole("dialog", { name: "Item overview" })
  await expect(detail.locator(".item-history-entry")).toHaveCount(0)
  await detail.getByRole("button", { name: "History", exact: true }).click()
  const history = page.getByRole("dialog", { name: "Item history", exact: true })
  await history.getByRole("button", { name: "Load earlier history", exact: true }).click()
  await expect(history.getByRole("status")).toContainText("No earlier archived versions")
  await expect(detail.getByRole("heading", { name: "Reversible item", exact: true })).toBeVisible()
  await expect(page.getByRole("region", { name: "To do" }).getByText("Reversible item")).toBeVisible()
})

test("Given three workspaces, when sharing A and B while viewing Private, then only selected documents arrive and stay independent", async ({ browser, page }) => {
  test.setTimeout(60_000)
  await page.route("**/api/sync-signal**", route => route.fulfill({ status: 404 }))
  await page.goto("/")
  const workspaceIds = new Map<string, string>()
  for (const title of ["Shared A", "Shared B", "Private"]) {
    await page.getByRole("button", { name: "Open workspaces" }).click()
    await page.getByRole("button", { name: "New workspace" }).click()
    const create = page.getByRole("dialog", { name: "Create workspace" })
    await create.getByLabel("Title", { exact: true }).fill(title)
    await create.getByRole("button", { name: "Create", exact: true }).click()
    await expect(page.getByRole("heading", { name: `TINCANBAN // ${title}`, exact: true })).toBeVisible()
    workspaceIds.set(title, await page.evaluate(async () => (await import("/src/state.ts")).useTincanban().activeWorkspace.id))
    await page.getByRole("button", { name: /Add item to/ }).first().click()
    const item = page.getByRole("dialog", { name: "Item details" })
    await item.getByLabel("Title *").fill(`${title} card`)
    await item.getByRole("button", { name: "Save item" }).click()
  }
  await page.getByRole("button", { name: "Sync", exact: true }).click()
  const hostDialog = page.getByRole("dialog", { name: "Device sync" })
  await hostDialog.getByRole("button", { name: "Add someone" }).click()
  await hostDialog.getByLabel("Private", { exact: true }).uncheck()
  await hostDialog.getByLabel("Shared A", { exact: true }).check()
  await hostDialog.getByLabel("Shared B", { exact: true }).check()
  await hostDialog.getByRole("button", { name: "Generate link" }).click()
  const invite = await hostDialog.getByLabel("Pairing link").inputValue()
  const guestContext = await browser.newContext()
  await guestContext.route("**/api/sync-signal**", route => route.fulfill({ status: 404 }))
  try {
    const guest = await guestContext.newPage()
    await guest.goto(invite)
    const dialog = guest.getByRole("dialog", { name: "Device sync" })
    await dialog.getByRole("button", { name: "Accept and join" }).click()
    await page.getByLabel("Participant role").selectOption("editor")
    await page.getByRole("button", { name: "Approve access" }).click()
    await expect(dialog.getByText(/Connected to/)).toBeVisible({ timeout: 25_000 })
    await dialog.getByRole("button", { name: "Close", exact: true }).first().click()
    for (const title of ["Shared A", "Shared B"]) {
      await guest.getByRole("button", { name: "Open workspaces" }).click()
      const workspaces = guest.getByRole("dialog", { name: "Workspaces" })
      await expect(workspaces.getByRole("button", { name: "Private", exact: true })).toHaveCount(0)
      await workspaces.locator(`.workspace-item[data-workspace-id="${workspaceIds.get(title)}"] .workspace-switch`).click()
      await expect(guest.getByRole("button", { name: `Open ${title} card`, exact: true })).toBeVisible()
      await expect(guest.getByRole("button", { name: "Open Private card", exact: true })).toHaveCount(0)
    }
    await hostDialog.getByRole("button", { name: "Close", exact: true }).first().click()
    await expect(page.getByRole("heading", { name: "TINCANBAN // Private", exact: true })).toBeVisible()
  } finally {
    await guestContext.close()
  }
})

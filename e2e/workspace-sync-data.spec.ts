test("Given both devices have independent populated workspaces, when joining, then random IDs keep the local one separate without conflict renaming", async ({ browser, page }) => {
  test.setTimeout(60_000)
  await page.goto("/")
  await addLead(page, "Host workspace card")
  const hostWorkspaceId = await page.evaluate(async () => (await import("/src/state.ts")).useTincanban().activeWorkspace.id)
  await page.getByRole("button", { name: "Sync", exact: true }).click()
  const host = page.getByRole("dialog", { name: "Device sync" })
  await host.getByRole("button", { name: "Add someone" }).click()
  await host.getByRole("button", { name: "Generate link" }).click()
  const invite = await host.getByLabel("Pairing link").inputValue()
  const context = await browser.newContext()
  try {
    const guest = await context.newPage()
    await guest.goto("/")
    await createJobSearchWorkspace(guest, "Guest jobs")
    const guestWorkspaceId = await guest.evaluate(async () => (await import("/src/state.ts")).useTincanban().activeWorkspace.id)
    await addLeadToActiveWorkspace(guest, "Guest local card")
    await guest.goto(invite)
    const dialog = guest.getByRole("dialog", { name: "Device sync" })
    await dialog.getByRole("button", { name: "Accept and join" }).click()
    await page.getByLabel("Participant role").selectOption("editor")
    await page.getByRole("button", { name: "Approve access" }).click()
    await expect(dialog.getByText("Connected to Job search")).toBeVisible({ timeout: 25_000 })
    await dialog.getByRole("button", { name: "Close", exact: true }).first().click()
    await expect(guest.getByRole("button", { name: "Open Host workspace card — Engineer" })).toBeVisible()
    await expect(guest.getByRole("button", { name: "Open Guest local card — Engineer" })).toHaveCount(0)
    await guest.getByRole("button", { name: "Open workspaces" }).click()
    const workspaces = guest.getByRole("dialog", { name: "Workspaces" })
    const hostWorkspace = workspaces.locator(`.workspace-item[data-workspace-id="${hostWorkspaceId}"]`)
    const guestWorkspace = workspaces.locator(`.workspace-item[data-workspace-id="${guestWorkspaceId}"]`)
    await expect(hostWorkspace).toHaveCount(1)
    await expect(hostWorkspace.locator(".workspace-switch strong")).toHaveText("jobs")
    await expect(guestWorkspace).toHaveCount(1)
    await expect(guestWorkspace.locator(".workspace-switch strong")).toHaveText("Guest jobs")
    await expect(workspaces.getByText(/\(local\)/)).toHaveCount(0)
    await guestWorkspace.locator(".workspace-switch").click()
    await expect(guest.getByRole("button", { name: "Open Guest local card — Engineer" })).toBeVisible()
    await expect(guest.getByRole("button", { name: "Open Host workspace card — Engineer" })).toHaveCount(0)
  } finally {
    await context.close()
  }
})


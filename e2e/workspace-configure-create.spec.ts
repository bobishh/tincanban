test("Given initial workspace persistence is pending, when Create is submitted again, then duplicate submission stays disabled", async ({ page }) => {
  await page.goto("/")
  await page.getByRole("button", { name: "Open workspaces" }).click()
  await page.getByRole("button", { name: "New workspace" }).click()
  const dialog = page.getByRole("dialog", { name: "Create workspace" })
  await dialog.getByLabel("Title", { exact: true }).fill("One board")
  await dialog.getByRole("button", { name: "Customize board" }).click()
  await dialog.getByLabel("Item name", { exact: true }).fill("task")
  await page.evaluate(async () => {
    const gate: { reached: boolean; release?: () => void } = { reached: false }
    ;(window as any).__testStorageGate = gate
    const storage = await import("/src/storage.ts")
    const prototype = storage.WorkspaceStorage.prototype as any
    const save = prototype.commitWorkspace
    prototype.commitWorkspace = async function (...args: any[]) {
      gate.reached = true
      await new Promise<void>(resolve => { gate.release = resolve })
      return save.apply(this, args)
    }
  })
  await dialog.locator("form").evaluate(form => {
    (form as HTMLFormElement).requestSubmit()
    ;(form as HTMLFormElement).requestSubmit()
  })
  await expect.poll(() => page.evaluate(() => (window as any).__testStorageGate?.reached)).toBe(true)
  await expect(dialog.getByRole("button", { name: "Creating…" })).toBeDisabled()
  await expect(dialog.getByRole("button", { name: "Create", exact: true })).toHaveCount(0)
  await expect(dialog.getByLabel("Title", { exact: true })).toBeDisabled()
  await expect(dialog.getByRole("button", { name: "Customize board" })).toBeDisabled()
  await page.evaluate(() => { (window as any).__testStorageGate.release() })
  await expect(dialog).toBeHidden()
  await page.getByRole("button", { name: "Open workspaces" }).click()
  await expect(page.getByRole("dialog", { name: "Workspaces" }).locator(".workspace-item", { hasText: "One board" })).toHaveCount(1)
})

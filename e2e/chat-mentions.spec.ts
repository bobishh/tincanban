import { expect, test } from "./support/coverage"
import { createJobSearchWorkspace } from "./support/workspaces"

for (const width of [390, 1440]) test(`Given ${width}px chat, when typing @, then participants appear inline and keyboard selection preserves the draft without sending`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto("/")
  await createJobSearchWorkspace(page, "Inline mentions")
  await page.getByRole("button", { name: "Workspace chat", exact: true }).filter({ visible: true }).click()
  const chat = page.getByRole("dialog", { name: "Workspace chat", exact: true })
  const composer = chat.getByRole("textbox", { name: "Message", exact: true })
  await expect(chat.getByText("Attach item reference", { exact: true })).toHaveCount(0)
  await expect(chat.getByText("Invite @participant", { exact: true })).toHaveCount(0)
  await composer.fill("Email me@example.com")
  await expect(chat.getByRole("listbox", { name: "Participants" })).toHaveCount(0)
  await composer.fill("Hello @no_such_participant")
  await expect(chat.getByRole("status", { name: "Participant search" })).toHaveText("No participants found")
  await composer.press("Escape")
  await expect(chat).toBeVisible()
  await expect(chat.getByRole("listbox", { name: "Participants" })).toHaveCount(0)
  await composer.fill("Hello @")
  await expect(chat.getByRole("listbox", { name: "Participants" })).toBeVisible()
  await composer.press("Shift+Enter")
  await expect(composer).toHaveValue("Hello @\n")
  await expect(chat.getByRole("listbox", { name: "Participants" })).toHaveCount(0)
  await expect(chat.locator(".chat-message-item")).toHaveCount(0)
  await composer.fill("Hello @")
  const choices = chat.getByRole("listbox", { name: "Participants" })
  const participant = await choices.getByRole("option").first().innerText()
  const query = participant.trim().slice(0, 2).toLocaleUpperCase()
  await composer.fill(`Hello @${query} tomorrow`)
  await composer.evaluate((input, caret) => {
    const textarea = input as HTMLTextAreaElement
    textarea.setSelectionRange(caret, caret)
    textarea.dispatchEvent(new Event("click", { bubbles: true }))
  }, 7 + query.length)
  await expect(choices).toContainText(participant.trim())
  await page.screenshot({ path: info.outputPath(`inline-mention-${width}.png`) })
  await composer.press("ArrowDown")
  await composer.press("Enter")
  await expect(composer).toHaveValue(`Hello @${participant.trim()} tomorrow`)
  await expect(choices).toHaveCount(0)
  await expect(chat.locator(".chat-message-item")).toHaveCount(0)
  await expect(composer).toBeFocused()
  await chat.getByRole("button", { name: "Send message", exact: true }).click()
  await expect(chat.getByText("Saving locally…")).toHaveCount(0)
  const context = await page.evaluate(async () => {
    const service = await import("/src/chat/service.ts")
    const app = (await import("/src/test/stateFixture.ts")).useTincanban()
    return (await service.loadChat(app.activeWorkspace.id)).messages.at(-1)!.context
  })
  expect(context?.mentions).toHaveLength(1)
})
